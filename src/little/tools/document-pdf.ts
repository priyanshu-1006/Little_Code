import { access } from 'node:fs/promises';
import * as path from 'node:path';
import { Worker } from 'node:worker_threads';
import { LittleError } from '../shared/errors';
import { assertNotAborted } from './workspace-service';
import { DOCUMENT_LIMITS, documentFailure, documentRange, validDocumentText, type DocumentExtraction, type DocumentRange } from './document-common';

type PdfJob = { mode: 'extract'; bytes: Uint8Array; range: DocumentRange } | { mode: 'generate'; content: string; bytes?: Uint8Array };
type PdfResult = { extraction: DocumentExtraction } | { bytes: Uint8Array };
/** Host-only controls for shorter deadlines and lifecycle inspection. These are
 * never accepted from a tool/model request and cannot expand production bounds. */
export interface PdfWorkerHostOptions { timeoutMs?: number; onWorkerStarted?: (worker: Worker) => void }
async function exists(file: string) { return access(file).then(() => true, () => false); }

export async function runPdfWorker(job: PdfJob, signal?: AbortSignal, options: PdfWorkerHostOptions = {}): Promise<PdfResult> {
  assertNotAborted(signal);
  if (job.bytes && (!(job.bytes instanceof Uint8Array) || job.bytes.length > DOCUMENT_LIMITS.maxFileBytes)) throw new LittleError('CONTEXT_LIMIT', 'The PDF exceeds the bounded document size.');
  if (job.mode === 'extract') documentRange(job.range); else validDocumentText(job.content);
  const builtWorker = path.join(__dirname, 'document-pdf-worker.cjs');
  const builtAssets = path.join(__dirname, 'pdf');
  const packaged = await exists(builtWorker) && await exists(path.join(builtAssets, 'pdf.mjs'));
  assertNotAborted(signal);
  const assetRoot = packaged ? builtAssets : path.resolve(__dirname, '../../../node_modules/pdfjs-dist/legacy/build');
  const input = job.bytes ? Uint8Array.from(job.bytes) : undefined;
  const workerData = { ...job, bytes: input, assetRoot, resourceRoot: packaged ? assetRoot : path.resolve(assetRoot, '../..') };
  const workerOptions = { workerData, transferList: input ? [input.buffer] : [], resourceLimits: { maxOldGenerationSizeMb: 192, maxYoungGenerationSizeMb: 32 } };
  // Source tests use the installed loader. Production loads only the packaged,
  // byte-verified worker; PDF-controlled data is never evaluated as JavaScript.
  const worker = packaged ? new Worker(builtWorker, workerOptions)
    : new Worker(`require('tsx/cjs');require(${JSON.stringify(path.join(__dirname, 'document-pdf-worker.ts'))});`, { ...workerOptions, eval: true });
  return new Promise((resolve, reject) => {
    let settled = false;
    const finish = (error?: LittleError, result?: PdfResult) => {
      if (settled) return; settled = true;
      clearTimeout(timer); signal?.removeEventListener('abort', cancel);
      // Returning source, generated bytes, cancellation or failure always waits
      // for termination. No parser job survives after the tool has settled.
      void worker.terminate().then(() => { if (error) reject(error); else resolve(result!); }, () => reject(new LittleError('TOOL_FAILED', 'The isolated PDF worker could not stop safely.')));
    };
    const cancel = () => finish(new LittleError('AGENT_CANCELLED', 'Document processing stopped.'));
    const timeout = Number.isSafeInteger(options.timeoutMs) ? Math.max(1, Math.min(options.timeoutMs!, DOCUMENT_LIMITS.pdfTimeoutMs)) : DOCUMENT_LIMITS.pdfTimeoutMs;
    const timer = setTimeout(() => finish(new LittleError('CONTEXT_LIMIT', 'PDF processing exceeded its bounded processing time. Try a smaller text-based PDF.')), timeout);
    signal?.addEventListener('abort', cancel, { once: true });
    worker.once('message', (message: unknown) => {
      if (!message || typeof message !== 'object') { finish(new LittleError('TOOL_FAILED', 'PDF processing failed safely.')); return; }
      const result = message as { ok?: boolean; extraction?: DocumentExtraction; bytes?: Uint8Array; reason?: string };
      if (result.ok && job.mode === 'extract' && result.extraction?.format === 'pdf'
        && Number.isSafeInteger(result.extraction.totalUnits) && result.extraction.totalUnits >= 1 && result.extraction.totalUnits <= DOCUMENT_LIMITS.maxPdfPages
        && Array.isArray(result.extraction.sections)) { finish(undefined, { extraction: result.extraction }); return; }
      if (result.ok && job.mode === 'generate' && result.bytes instanceof Uint8Array && result.bytes.length > 0 && result.bytes.length <= DOCUMENT_LIMITS.maxFileBytes) { finish(undefined, { bytes: result.bytes }); return; }
      const reason = result.reason;
      const error = reason === 'no_text' ? new LittleError('TOOL_FAILED', 'This PDF range has no extractable text, possibly because it is scanned. OCR is unavailable.')
        : reason === 'invalid_range' ? new LittleError('TOOL_VALIDATION_FAILED', 'The requested starting page is beyond the PDF.')
          : reason === 'unsupported_character' ? new LittleError('TOOL_VALIDATION_FAILED', 'PDF generation supports the bundled standard-font character set. Use DOCX/PPTX for unsupported Unicode characters.')
            : reason?.startsWith('bounded_') ? new LittleError('CONTEXT_LIMIT', 'The PDF exceeds the bounded size, page or source-text limit.')
              : new LittleError('TOOL_FAILED', 'The PDF is corrupt, encrypted or unsupported. No PDF content was returned.');
      finish(error);
    });
    worker.once('error', () => finish(new LittleError('TOOL_FAILED', 'PDF processing failed within its isolated worker. No document content was returned.')));
    worker.once('exit', () => { if (!settled) finish(new LittleError('TOOL_FAILED', 'The bounded PDF worker stopped without returning a result.')); });
    try { options.onWorkerStarted?.(worker); } catch { finish(new LittleError('TOOL_FAILED', 'PDF processing could not start safely.')); }
    if (signal?.aborted) cancel();
  });
}
export async function extractPdf(bytes: Uint8Array, range: DocumentRange = {}, signal?: AbortSignal): Promise<DocumentExtraction> {
  assertNotAborted(signal); documentRange(range);
  if (bytes.length > DOCUMENT_LIMITS.maxFileBytes) throw new LittleError('CONTEXT_LIMIT', 'The PDF exceeds the bounded document size.');
  if (!Buffer.from(bytes.subarray(0, 1024)).includes(Buffer.from('%PDF-'))) documentFailure('The file is not a supported PDF document.');
  const result = await runPdfWorker({ mode: 'extract', bytes, range }, signal);
  if (!('extraction' in result)) documentFailure();
  return result.extraction;
}
export async function generatePdf(content: string, original?: Uint8Array, signal?: AbortSignal): Promise<Uint8Array> {
  const result = await runPdfWorker({ mode: 'generate', content, bytes: original }, signal);
  if (!('bytes' in result)) documentFailure();
  return result.bytes;
}
